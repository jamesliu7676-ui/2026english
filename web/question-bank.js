window.pickDiagnosticQuestions = function pickDiagnosticQuestions(selectedLevel) {
  const bank = window.diagnosticQuestionBank || [];
  const skills = window.diagnosticSkills || [];
  const levels = window.diagnosticLevels || [];
  const targetIndex = levels.indexOf(selectedLevel);
  const allowedLevels = targetIndex === -1 ? levels : levels.slice(0, targetIndex + 1);

  function shuffle(items) {
    return [...items].sort(() => Math.random() - 0.5);
  }

  return skills.flatMap((skill) => {
    const matching = bank.filter((question) => {
      return question.skill === skill && allowedLevels.includes(question.level);
    });
    return shuffle(matching).slice(0, 4);
  });
};
